# 去重 + 过滤私用区/兼容区等字体不含的码点
seen = set()
result = []
def add(c):
    cp = ord(c)
    if c in seen:
        return
    if cp < 0x20:
        return
    if 0xE000 <= cp <= 0xF8FF:  # 私用区
        return
    if 0xF900 <= cp <= 0xFAFF:  # 兼容表意
        return
    seen.add(c)
    result.append(c)
